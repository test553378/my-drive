export const vehicle = (model) => VEHICLES[model] || VEHICLES[0];
export function wheelLayout(model, wide = 0) {
  const s = vehicle(model),
    half = s.width * 0.46 + (wide ? 0.1 : 0);
  return s.wheelZ.flatMap((z) =>
    s.wheels === 2
      ? [{ x: 0, z }]
      : [
          { x: -half, z },
          { x: half, z },
        ],
  );
}
